const BATCHES = [
  { owner: 'Alex', institution: 'Chase', name: 'Sapphire', mask: '4417', txns: chase },
  { owner: 'Joint', institution: 'Ally', name: 'Checking', mask: '8820', txns: ally },
  { owner: 'Sam', institution: 'Amex', name: 'Everyday', mask: '1004', txns: amex },
];

async function main(): Promise<void> {
  const file = assertDisposableTarget();

  // Start from nothing: ingest's fingerprint dedupe would otherwise skip every
  // row on a rerun, leaving whatever the previous run produced in place.
  for (const suffix of ['', '-shm', '-wal']) fs.rmSync(`${file}${suffix}`, { force: true });
  fs.mkdirSync(path.dirname(file), { recursive: true });
  runMigrations();

  let total = 0;
  for (const b of BATCHES) {
    const { added } = await ingestClassifiedBatch({
      account: {
        institution: b.institution,
        name: b.name,
        owner: b.owner,
        mask: b.mask,
        accountClass: 'spending',
        type: b.institution === 'Amex' ? 'credit' : 'depository',
      },
      source: 'manual',
      transactions: b.txns,
    });
    total += added;
    // eslint-disable-next-line no-console
    console.log(`  ${b.owner} ${b.institution} ${b.name}: ${added} transactions`);
  }
  // eslint-disable-next-line no-console
  console.log(`Seeded ${total} demo transactions into ${path.relative(process.cwd(), file)}`);
}

void main().catch((err) => {
  // eslint-disable-next-line no-console
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
