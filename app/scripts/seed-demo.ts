/**
 * Rebuilds the fake demo dataset behind the README screenshots.
 *
 * Run it with `npm run demo:seed` (or via `npm run screenshots`, which seeds
 * and then captures). Everything below is invented — no real merchant,
 * account, or amount appears anywhere in it.
 *
 * ## Where this writes
 *
 * `data/demo/demo.db`, never `data/app.db`. Two reasons, both learned the hard
 * way elsewhere in this repo (see the comment block in playwright.config.ts):
 *
 *   1. This script DROPS its database and rebuilds it from nothing. Pointed at
 *      the live file that is a total loss of the user's financial history, so
 *      the live file must be unreachable from here by construction, not by
 *      remembering to set an env var. Hence the default below and the
 *      assertion in `assertDisposableTarget`.
 *   2. It gets its own *directory*, not just its own filename, because
 *      `exportRules()` mirrors preferences.json next to the resolved database
 *      file rather than next to DATABASE_URL. A demo db sitting directly in
 *      `data/` could therefore overwrite the real `data/preferences.json`.
 *
 * ## Why the numbers are what they are
 *
 * The shape is pinned to `docs/screenshots/accounts.png`, which is not
 * regenerated by the capture script (that page shows no category colors, so a
 * theme change never invalidates it). Same three accounts, same per-account
 * counts (86 / 40 / 65 = 191), same Jul 2025 – Jun 2026 window. Change those
 * and accounts.png quietly starts lying about the app.
 */
import fs from 'fs';
import path from 'path';

// Set BEFORE the db client resolves anything. Safe as a plain statement even
// though imports hoist above it: getDb() is lazy and memoizes on first call,
// and nothing in this module's import graph calls it at import time.
// `assertDisposableTarget` re-checks the resolved path at runtime regardless,
// so an eager caller introduced later still cannot reach the live database.
process.env.DATABASE_URL ??= 'file:./data/demo/demo.db';

import { resolveDbFile } from '@/db/client';
import { runMigrations } from '@/db/migrate';
import { ingestClassifiedBatch, type IngestTxn } from '@/lib/ingest';

/** Abort unless the resolved database is one this script may destroy. */
function assertDisposableTarget(): string {
  const file = resolveDbFile();
  const dir = path.basename(path.dirname(file));
  if (dir !== 'demo') {
    throw new Error(
      `Refusing to seed ${file}.\n` +
        'This script deletes its database and rebuilds it. It will only touch a\n' +
        "file inside a directory named 'demo' (default: data/demo/demo.db).\n" +
        'Unset DATABASE_URL, or point it at a demo directory.',
    );
  }
  return file;
}

// Deterministic PRNG: rerunning reproduces byte-identical screenshots, so a
// refresh diffs as "the theme changed", not "the fake data moved around too".
let seedState = 20260814;
const rand = () => {
  seedState = (seedState * 1664525 + 1013904223) % 4294967296;
  return seedState / 4294967296;
};

const MONTHS: string[] = [];
for (let i = 6; i < 12; i++) MONTHS.push(`2025-${String(i + 1).padStart(2, '0')}`);
for (let i = 0; i < 6; i++) MONTHS.push(`2026-${String(i + 1).padStart(2, '0')}`);

const day = (d: number) => String(d).padStart(2, '0');

/**
 * `count` amounts that vary but sum to exactly `total`, so category totals land
 * on the round figures the charts label.
 */
function split(total: number, count: number): number[] {
  const weights = Array.from({ length: count }, () => 0.75 + rand() * 0.5);
  const sum = weights.reduce((a, b) => a + b, 0);
  const out = weights.map((w) => Math.round(((total * w) / sum) * 100) / 100);
  const drift = Math.round((total - out.reduce((a, b) => a + b, 0)) * 100) / 100;
  out[out.length - 1] = Math.round((out[out.length - 1] + drift) * 100) / 100;
  return out;
}

/**
 * Spread `count` transactions over the 12 months, cycling merchants.
 *
 * A count that divides evenly into 12 is treated as a recurring bill (rent,
 * electric, a streaming plan) and cycles the months in order — one per month.
 * Everything else scatters at random. Cycling the one-offs too piles every
 * single-instance category (the 3 flights, the 2 pharmacy runs) into the first
 * months of the range, which rendered as a spending line sloping steadily
 * downhill for no reason a reader could infer.
 */
function spend(
  count: number,
  total: number,
  categoryId: string,
  subcategoryId: string,
  merchants: string[],
): IngestTxn[] {
  const recurring = count % MONTHS.length === 0;
  return split(total, count).map((amount, i) => ({
    date: `${
      recurring ? MONTHS[i % MONTHS.length] : MONTHS[Math.floor(rand() * MONTHS.length)]
    }-${day(2 + Math.floor(rand() * 26))}`,
    description: merchants[i % merchants.length],
    amount: -amount,
    categoryId,
    subcategoryId,
  }));
}

